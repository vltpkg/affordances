import path from 'node:path'
import { defineDocs } from 'fumadocs-mdx/macro'
import { applyMdxPreset } from 'fumadocs-mdx/config'
import { loader } from 'fumadocs-core/source'
import type * as PageTree from 'fumadocs-core/page-tree'
import { getBreadcrumbItems } from 'fumadocs-core/breadcrumb'
import { createFromSource } from 'fumadocs-core/search/server'

// the slice of a hast node rehypeCodeMeta touches (hast types aren't a direct dependency)
type HastNode = {
  type: string
  tagName?: string
  data?: { meta?: string | null }
  properties?: Record<string, unknown>
  children?: HastNode[]
}

// a fence's meta (```ts title="app/actions.ts") isn't a prop, so lift its title onto the <code>
const rehypeCodeMeta = () => (tree: HastNode) => {
  const walk = (node: HastNode) => {
    const title = node.tagName === 'code' && node.data?.meta?.match(/title="([^"]*)"/)?.[1]
    if (title) node.properties = { ...node.properties, title }
    node.children?.forEach(walk)
  }
  walk(tree)
}

// the slice of an mdast node remarkFileLinks touches
type MdNode = { type: string; url?: string; children?: MdNode[] }

const contentDir = path.resolve('content')

// typedoc links its pages to each other by file (`reference.md`, `../core/index.md#createhandler`); point
// those at the pages' urls instead, which also keeps them off /x.md (the markdown twin)
const remarkFileLinks = () => (tree: MdNode, file: { path?: string }) => {
  const walk = (node: MdNode) => {
    const [target = '', hash] = node.url?.split('#') ?? []
    if (node.type === 'link' && file.path && /^[^/#:]+.*\.mdx?$/i.test(target)) {
      const page = path
        .relative(contentDir, path.resolve(path.dirname(file.path), target))
        .replace(/\.mdx?$/i, '')
        .replace(/(^|\/)index$/, '')
      node.url = `/docs${page ? `/${page}` : ''}${hash ? `#${hash}` : ''}`
    }
    node.children?.forEach(walk)
  }
  walk(tree)
}

const docs = defineDocs({
  dir: 'content',
  docs: {
    // @afford/ui's CodeBlock highlights on the server, so fumadocs' shiki (rehype-code) is off
    mdxOptions: applyMdxPreset({
      rehypeCodeOptions: false,
      remarkPlugins: [remarkFileLinks],
      rehypePlugins: [rehypeCodeMeta],
    }),
  },
})

// the docs live under /docs; / is the marketing page and /agents the agents' start page
export const source = loader({
  baseUrl: '/docs',
  source: docs.toFumadocsSource(),
  pageTree: {
    transformers: [
      {
        // a section's index sits first under its separator, which already says the section's name
        file: (node, filePath) =>
          filePath && /^(concepts|guides|reference)\/index\.mdx$/.test(filePath)
            ? { ...node, name: 'Overview' }
            : node,
      },
    ],
  },
})

// a docs url (/docs, /docs/concepts/actions) to its page
export const pageFor = (url: string) => {
  const [base, ...slug] = url.split('/').filter(Boolean)
  return base === 'docs' ? source.getPage(slug) : undefined
}

// content/meta.json groups pages under `---Label---` separators; each separator links to the page (or
// folder) after it
const groupUrls = new Map(
  source.pageTree.children.flatMap((node, i, nodes) => {
    if (node.type !== 'separator') return []
    const next = nodes[i + 1]
    const url =
      next?.type === 'page' ? next.url : next?.type === 'folder' ? next.index?.url : undefined
    return url ? [[node.name, url] as const] : []
  }),
)

// generated by scripts/typedoc.mts; llms.txt lists these pages, llms-full.txt and the root graph don't
export const isApiReference = (url: string) => url.startsWith('/docs/reference/api-reference')

// a page's place in the sidebar, e.g. Concepts / Deltas, ending with the page itself
export const breadcrumbs = (url: string) =>
  getBreadcrumbItems(url, source.pageTree, { includePage: true, includeSeparator: true }).map(
    (item) => ({ ...item, url: item.url ?? groupUrls.get(item.name) }),
  )

type Section = { title: string; pages: { title: string; url: string; description?: string }[] }

// the sidebar's groups, as data, in sidebar order: what the root graph and llms.txt list. pages before the
// first separator are "Get started"; a folder contributes its index and pages (and its folders') in place
export const sections = () => {
  const groups: Section[] = [{ title: 'Get started', pages: [] }]
  const add = (item: PageTree.Item, prefix = '') => {
    const page = source.getNodePage(item)
    groups.at(-1)!.pages.push({
      title: `${prefix}${String(item.name)}`,
      url: item.url,
      ...(page?.data.description && { description: page.data.description }),
    })
  }
  const walk = (nodes: PageTree.Node[], prefix = '') => {
    for (const node of nodes) {
      if (node.type === 'separator') groups.push({ title: String(node.name), pages: [] })
      else if (node.type === 'page') add(node, prefix)
      else {
        if (node.index) add(node.index, prefix)
        // a folder's pages are named for what they are inside it ("Setup"), so say which folder
        walk(node.children, `${prefix}${String(node.name)}: `)
      }
    }
  }
  walk(source.pageTree.children)
  return groups.filter((group) => group.pages.length)
}

const index = createFromSource(source, {
  buildIndex: (page) => ({
    id: page.url,
    url: page.url,
    title: page.data.title,
    description: page.data.description,
    structuredData: page.data.structuredData,
  }),
})

// table rows come back as raw markdown rows, which read as noise in results; their pages still match by text
export const search = async (query: string) =>
  (await index.search(query)).filter((result) => !result.table)
