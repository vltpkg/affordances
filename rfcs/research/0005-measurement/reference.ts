// RFC 0005 §7: hosting-lab's reference, made mechanically from its hand-written manifest (SCORING.md §2). Each
// capability's binding is the route and action of the real hosting-lab's bound action for it, as the extractor
// reports them. SPIKE: measurement input, run once, before the measurement, with
//   node --experimental-strip-types rfcs/research/0005-measurement/reference.ts
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { manifest } from '../../../apps/hosting-lab/src/app/capabilities.ts'
import { extract } from '../../../packages/next/src/extract.ts'

const here = import.meta.dirname
const app = path.join(here, '..', '..', '..', 'apps', 'hosting-lab')

// the bound actions' capabilities, by the name capabilities.ts exports them as, to their binding
const bound = extract(app).bound
const exportName = new Map<string, string>()
const capabilityModule = await import('../../../apps/hosting-lab/src/app/capabilities.ts')
for (const [name, value] of Object.entries(capabilityModule))
  if (value && typeof value === 'object' && 'definition' in value)
    exportName.set(name, (value as { definition: { id: string } }).definition.id)
const bindingOf = new Map<string, { route: string; action: string }>()
for (const b of bound) {
  const id = exportName.get(b.capability.imported ?? b.capability.local)
  if (id) bindingOf.set(id, { route: b.route, action: b.action })
}

const withoutSchema = (schema: unknown) => {
  if (!schema || typeof schema !== 'object') return schema ?? null
  const { $schema: _drop, ...rest } = schema as Record<string, unknown>
  return rest
}

const reference = {
  about:
    "RFC 0005 §7's reference for apps/hosting-lab, generated by reference.ts from its hand-written manifest (src/app/capabilities.ts) and its bound actions' bindings, before the measurement ran (SCORING.md §2).",
  spike: 'SPIKE: measurement input for assumption 8, not product code.',
  namespace: manifest.namespace,
  resources: manifest.resources.map((r) => ({
    id: r.id,
    key: r.key,
    from: null,
    attributes: Object.keys(
      (r.attributes as { properties?: Record<string, unknown> } | undefined)?.properties ?? {},
    ),
  })),
  // only capabilities a bound action implements: the rest (a query or an event no action binds) have no v0 form
  capabilities: manifest.capabilities
    .filter((c) => bindingOf.has(c.id))
    .map((c) => ({
      id: c.id,
      kind: c.kind,
      description: c.description,
      binding: bindingOf.get(c.id)!,
      target: c.target ?? null,
      input: withoutSchema(c.input),
      authorization: c.authorization ? { principal: c.authorization.principal } : null,
      confirmation: c.confirmation ? { summary: c.confirmation.summary } : null,
      preconditions: (c.preconditions ?? []).map((p) => ({
        id: p.id,
        description: p.description,
        declarative: !('guard' in p && p.guard),
      })),
      effects: c.effects ?? [],
      claims: (manifest.claims ?? [])
        .filter((claim) => claim.subject === c.id)
        .map(({ provenance: _p, ...claim }) => claim),
      relations: (manifest.relations ?? [])
        .filter((r) => r.from === c.id || r.to === c.id)
        .map(({ provenance: _p, ...r }) => r),
    })),
}

writeFileSync(
  path.join(here, 'hosting-lab-reference.json'),
  `${JSON.stringify(reference, null, 2)}\n`,
)
console.log(
  `${reference.capabilities.length} capabilities, ${reference.resources.length} resources`,
)
