import { readdirSync, readFileSync } from 'node:fs'
import { describe, expect, test } from 'vitest'
import { canonicalJson } from '../src/canonical.ts'
import { normalize } from '../src/normalize.ts'
import type { CapabilityManifest } from '../src/schema.ts'
import { validate } from '../src/validate.ts'

const fixture = (file: string): CapabilityManifest =>
  JSON.parse(readFileSync(new URL(`../fixtures/valid/${file}`, import.meta.url), 'utf8'))
const files = readdirSync(new URL('../fixtures/valid', import.meta.url))
const bytes = (m: CapabilityManifest) => canonicalJson(normalize(m))

describe('normalize', () => {
  test.each(files)('is idempotent on %s', (file) => {
    const once = normalize(fixture(file))
    expect(canonicalJson(normalize(once))).toBe(canonicalJson(once))
  })

  test.each(files)('keeps %s valid', (file) => {
    expect(validate(normalize(fixture(file))).ok).toBe(true)
  })

  test("RFC 0001's example is already canonical", () => {
    // §11 was generated by applying §7.2's rules, so normalizing changes nothing
    const example = fixture('rfc-0001-example.json')
    expect(bytes(example)).toBe(canonicalJson(example))
  })
})

// a seeded shuffle, so a failure reproduces
const shuffle = <T>(items: T[], seed: number): T[] => {
  const out = [...items]
  let s = seed
  for (let i = out.length - 1; i > 0; i--) {
    s = (s * 1103515245 + 12345) % 2 ** 31
    const j = s % (i + 1)
    ;[out[i], out[j]] = [out[j]!, out[i]!]
  }
  return out
}
// every array §7.2 calls a set, shuffled, and object members in reverse order
const SETS = new Set([
  'sources',
  'resources',
  'capabilities',
  'claims',
  'relations',
  'bindings',
  'contains',
  'references',
  'preconditions',
  'conditions',
  'effects',
  'evidence',
  'all',
  'any',
])
const scramble = (value: unknown, seed: number, key = ''): unknown => {
  if (Array.isArray(value)) {
    const items = value.map((v, i) => scramble(v, seed + i + 1))
    return SETS.has(key) ? shuffle(items, seed) : items
  }
  if (value && typeof value === 'object')
    return Object.fromEntries(
      Object.entries(value)
        .toReversed()
        .map(([k, v], i) => [
          k,
          k === 'input' || k === 'output' || k === 'attributes' ? v : scramble(v, seed + i, k),
        ]),
    )
  return value
}

describe('order never matters', () => {
  test.each(files)('%s gives the same bytes in any order', (file) => {
    const m = fixture(file)
    for (let seed = 1; seed <= 50; seed++)
      expect(bytes(scramble(m, seed) as CapabilityManifest)).toBe(bytes(m))
  })

  test('an alternativeTo gives the same bytes written either way round', () => {
    const m = fixture('plans.json')
    const edge = {
      type: 'alternativeTo' as const,
      from: 'hosting.plan.subscribe',
      to: 'hosting.plan.cancel',
    }
    const one = bytes({ ...m, relations: [edge] })
    const other = bytes({ ...m, relations: [{ ...edge, from: edge.to, to: edge.from }] })
    expect(one).toBe(other)
    expect(normalize({ ...m, relations: [edge] }).relations![0]!.from).toBe('hosting.plan.cancel')
  })

  test('relations that tie on their key are ordered by their bytes', () => {
    const m = fixture('plans.json')
    const a = {
      type: 'relatedTo' as const,
      from: 'hosting.plan.list',
      to: 'hosting.plan.cancel',
      description: 'a',
    }
    const b = { ...a, description: 'b' }
    expect(bytes({ ...m, relations: [a, b] })).toBe(bytes({ ...m, relations: [b, a] }))
  })
})

describe('defaults are dropped', () => {
  const m = fixture('plans.json')
  const sub = () => normalize(m).capabilities.find((c) => c.id === 'hosting.plan.subscribe')!

  test("a definition's provenance equal to the manifest's", () => {
    const withOwn = structuredClone(m)
    withOwn.capabilities[1]!.provenance = { source: 'host', basis: 'declared' }
    expect(bytes(withOwn)).toBe(bytes(m))
  })

  test("a field's provenance equal to its definition's", () => {
    const withField = structuredClone(m)
    withField.capabilities[1]!.fieldProvenance = {
      '/description': { source: 'host', basis: 'declared' },
    }
    expect(bytes(withField)).toBe(bytes(m))
  })

  test('empty optional arrays, but not effects: []', () => {
    const empty = structuredClone(m)
    empty.capabilities[2]!.references = []
    empty.capabilities[2]!.preconditions = []
    empty.relations = []
    const normal = normalize(empty)
    expect(normal.relations).toBeUndefined()
    expect(normal.capabilities.find((c) => c.id === 'hosting.plan.cancel')).not.toHaveProperty(
      'references',
    )
    expect(normal.capabilities.find((c) => c.id === 'hosting.plan.list')!.effects).toEqual([])
  })

  test('$schema in an embedded schema', () => {
    const withSchema = structuredClone(m)
    withSchema.capabilities[1]!.input = {
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      ...m.capabilities[1]!.input,
    }
    expect(bytes(withSchema)).toBe(bytes(m))
  })

  test('exact duplicates in a set', () => {
    const twice = structuredClone(m)
    twice.bindings!.push({ ...m.bindings![0]! })
    expect(bytes(twice)).toBe(bytes(m))
  })

  test('a query is completed: safe and no effects', () => {
    const bare = structuredClone(m)
    delete bare.capabilities[0]!.safe
    delete bare.capabilities[0]!.effects
    const list = normalize(bare).capabilities.find((c) => c.id === 'hosting.plan.list')!
    expect([list.safe, list.effects]).toEqual([true, []])
  })

  test('nothing else is dropped', () => {
    expect(sub().preconditions!.map((c) => c.id)).toEqual([
      'billing',
      'hasDomain',
      'member',
      'notCurrent',
      'regionUp',
      'seatsInRange',
    ])
  })
})
