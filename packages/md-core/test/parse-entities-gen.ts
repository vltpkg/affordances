// writes md's src/convert/core/entities-table.ts: every named character reference html knows, read out of the decode tree that parse5
// itself decodes with (the entities package, parse5's dependency), so the table is the oracle's by construction. run
// with `node test/parse-entities-gen.ts` from the package, then `oxfmt ../md/src/convert/core/entities-table.ts`
import { writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.resolve('parse5'))
const entities = (await import(require.resolve('entities/decode'))) as {
  EntityDecoder: new (
    tree: Uint16Array,
    emit: (cp: number) => void,
  ) => {
    startEntity(mode: number): void
    write(input: string, offset: number): number
    end(): number
  }
  htmlDecodeTree: Uint16Array
}
const LEGACY = 0
const STRICT = 1

let out = ''
const decoder = new entities.EntityDecoder(entities.htmlDecodeTree, (cp) => {
  out += String.fromCodePoint(cp)
})
// -1: the name so far could still become a reference; >0: it is one (the count includes the '&')
const run = (mode: number, text: string, end: boolean) => {
  out = ''
  decoder.startEntity(mode)
  let consumed = decoder.write(text, 0)
  if (consumed < 0 && end) consumed = decoder.end()
  return { consumed, value: out }
}

const ALNUM = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
const table: [string, string][] = []
const walk = (prefix: string) => {
  for (const char of ALNUM) {
    const name = prefix + char
    if (run(STRICT, name, false).consumed !== -1) continue
    const full = run(STRICT, `${name};`, false)
    if (full.consumed === name.length + 2) table.push([`${name};`, full.value])
    const legacy = run(LEGACY, name, true)
    if (legacy.consumed === name.length + 1) table.push([name, legacy.value])
    walk(name)
  }
}
walk('')
table.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const strict = table.filter(([name]) => name.endsWith(';')).length
// the html spec's table: 2125 names with ';' and 106 legacy ones without
if (strict !== 2125 || table.length - strict !== 106)
  throw new Error(`unexpected table: ${strict} with ';', ${table.length - strict} without`)

const body = table.map(([name, value]) => `  ${JSON.stringify(name)}: ${JSON.stringify(value)},`)
writeFileSync(
  new URL('../../md/src/convert/core/entities-table.ts', import.meta.url),
  `// generated by md-core's test/parse-entities-gen.ts from parse5's decode tree: every named character reference, the legacy ones
// (decoded without a ';') also under their bare name. do not edit
export const ENTITIES: Record<string, string> = {\n${body.join('\n')}\n}\n`,
)
console.log(`wrote ${table.length} names`)
