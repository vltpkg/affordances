export const treePages = (seed: number) => {
  let state = seed >>> 0 || 1
  const rnd = (n: number) => {
    state ^= state << 13
    state >>>= 0
    state ^= state >>> 17
    state ^= state << 5
    state >>>= 0
    return state % n
  }
  const pick = <T>(list: T[]) => list[rnd(list.length)]!
  const piece = () => {
    const r = rnd(10)
    return r < 5 ? pick(OPEN) : r < 7 ? `</${pick(CLOSE_TAGS)}>` : pick(TEXT)
  }
  return () => {
    let out = rnd(3) ? '<!doctype html>' : ''
    const n = 3 + rnd(40)
    for (let i = 0; i < n; i++) out += piece()
    return out
  }
}
